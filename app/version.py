"""Версия программы - одно место на всю программу.

При сборке на GitHub (packaging/stamp_version.py) сюда автоматически записываются номер
версии из названия релиза и адрес репозитория - по нему программа проверяет обновления.
"""
VERSION = "1.5.0"
GITHUB_REPO = ""    # "владелец/репозиторий"; пусто - проверка обновлений выключена
APP_NAME = "Виртуальный проводник"


def short_version(v=VERSION):
    """1.5.0 -> 1.5, 1.5.2 -> 1.5.2 (для заголовка окна)."""
    parts = v.split(".")
    while len(parts) > 2 and parts[-1] == "0":
        parts.pop()
    return ".".join(parts)
